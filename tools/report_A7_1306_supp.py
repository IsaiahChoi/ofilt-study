"""P2-5 supplement to check 2.1, A7 on 1306 (P17, P18; D9). TARGET-ONLY, dev.

Imports tools/report_A7_1306.py's functions and so applies the same hash check (the P2-4 dev panel against
its MANIFEST.json), the same column list (date, ticker, y_oc, y_topix_oc, y_1306_oc, earn_flag, news_flag)
and the same blinding assert. No predictor column is loaded. Requested by the supervisor message of
2026-10-05 (after the P2-5 report), item 2:
a. table (a'): beta estimated on ALL rows (eligible = None, as in part (a) of the TOPIX report), each window
   on its own evaluation rows, with n per cell; hedge 1306;
b. beta coverage on ALL dev rows (not only the evaluation rows), with beta on non-excluded rows as in the
   primary definition: per window and ticker, the rows with a finite beta, the rows without, and the first
   date with a finite beta; totals over the tickers; hedge 1306;
c. self-check: the same coverage count for hedge = y_topix_oc with the expanding window must give 774 rows
   without beta (PASS2_ADDENDUM B'; A5). If not, both numbers are reported and flagged (not a STOP).

Writes reports/A_hedge_efficiency_1306_supplement.md; modifies no committed report.
usage: python tools/report_A7_1306_supp.py
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "tools"))
import report_A7_1306 as R  # noqa: E402
from ofilt.drift import targets as TG  # noqa: E402
from ofilt.drift.spec import Spec  # noqa: E402

PREDICTOR_PREFIXES = ("usdjpy_", "eurusd_", "xau_", "n225_", "c_")
PREDICTORS = {"spy_oc", "ewj_oc", "fcx_oc", "copx_oc", "ewj_oc_jpy", "usdjpy_us_ret"}
A5_ROWS_WITHOUT_BETA = 774


def coverage(d, hedge, eligible):
    """Per window and ticker, on ALL dev rows: rows, rows with a finite beta, rows without, first date with one."""
    out = {}
    for w in R.BETA_WINDOWS:
        b = R.beta(d, w, hedge, eligible).to_numpy(dtype=float)
        rows = []
        for t in R.A7.TICKERS:
            k = (d.ticker == t).to_numpy()
            fin = k & np.isfinite(b)
            first = d.date[fin].min()
            rows.append((t, int(k.sum()), int(fin.sum()), int(k.sum() - fin.sum()),
                         first.strftime("%Y-%m-%d") if fin.any() else "none"))
        out[w] = rows
    return out


def main() -> int:
    d, manifest_sha, panel_sha = R.load()
    assert not [c for c in d.columns if c.startswith(PREDICTOR_PREFIXES) or c in PREDICTORS], "predictor column loaded"
    spec = Spec.load()
    elig = ~TG.exclusion_mask(d, spec)
    out = []
    say = out.append
    say("# A7 on 1306: supplement (dev, target-only)")
    say("")
    say(f"Generated by `tools/report_A7_1306_supp.py` (supervisor message of 2026-10-05 after the P2-5 report, item 2), "
        f"importing `tools/report_A7_1306.py`. Panel `build_out/{R.PANEL_DIR.name}/panel_dev.csv`, SHA-256-verified "
        f"against its MANIFEST (`{panel_sha}`; MANIFEST SHA-256 `{manifest_sha}`) before loading. Reads only "
        + ", ".join(f"`{c}`" for c in R.COLS) + "; no predictor column is loaded.")
    say("")
    say("Definitions are those of `reports/A_hedge_efficiency_1306.md` (tools/report_A7.py's, hedge passed explicitly). "
        "The β window is NOT decided here (D9 stays open).")
    say("")
    # (a')
    bb_all = {w: R.beta(d, w, "y_1306_oc", None) for w in R.BETA_WINDOWS}
    v, n = R.table(d, "y_1306_oc", bb_all)
    say("## (a′) 1306: β estimated on ALL rows (eligible = None), each window on its own evaluation rows")
    say("")
    say("As part (a) of the TOPIX report: `targets.past_beta(..., hedge=y_1306_oc, eligible=None)`, lag 1 day; evaluation "
        "rows date >= 2017-01-01, earn_flag == 0, news_flag == 0; value var(y_oc − β·y_1306_oc) × 1e8 (bp²), ddof 1, NaN β "
        "skipped; `none` = var(y_oc) on the same rows.")
    say("")
    say(R.fmt_tab(v, n))
    low = R.A7.lowest_is_expanding(v)
    say("")
    say(f"- Lowest variance among windows is `expanding` for ({', '.join(R.A7.TICKERS)}): {low}.")
    say("")
    # (b)
    cov = coverage(d, "y_1306_oc", elig)
    say("## (b) β coverage on ALL dev rows, β on non-excluded rows (primary definition); hedge 1306")
    say("")
    say("Rows = all dev rows of the ticker (not only the evaluation rows). A row has β if `targets.past_beta(..., "
        "hedge=y_1306_oc, eligible=~excl_inference)` is finite there.")
    say("")
    say("| window | ticker | rows | with β | without β | first date with β |")
    say("|---|---|---|---|---|---|")
    for w, rows in cov.items():
        for t, nr, nw, nwo, first in rows:
            say(f"| {w} | {t} | {nr} | {nw} | {nwo} | {first} |")
        say(f"| {w} | **total** | {sum(r[1] for r in rows)} | {sum(r[2] for r in rows)} | {sum(r[3] for r in rows)} | "
            f"{min(r[4] for r in rows)} |")
    say("")
    # (c)
    tcov = coverage(d, "y_topix_oc", elig)["expanding"]
    without = sum(r[3] for r in tcov)
    ok = without == A5_ROWS_WITHOUT_BETA
    say("## (c) Self-check: TOPIX, expanding")
    say("")
    say(f"Rows without β, hedge `y_topix_oc`, expanding, β on non-excluded rows, over the 3 tickers: {without} "
        f"(PASS2_ADDENDUM B′ / A5: {A5_ROWS_WITHOUT_BETA}); equal: {ok}. Per ticker: "
        + ", ".join(f"{t} {nwo}" for t, _, _, nwo, _ in tcov) + ".")
    if not ok:
        say("")
        say(f"**FLAG (not a STOP): {without} rows without β, against {A5_ROWS_WITHOUT_BETA}.**")
    say("")
    say("## Blinding")
    say("Target-only statistics (variances and β coverage counts) on dev. No predictor column was loaded.")
    text = "\n".join(out) + "\n"
    (ROOT / "reports" / "A_hedge_efficiency_1306_supplement.md").write_text(text, encoding="utf-8")
    print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
