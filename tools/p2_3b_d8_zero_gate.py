"""P2-3b item 1: the D8 zero-gap gate. GAP-ONLY, dev (supervisor message of 2026-10-05, decision checkpoint).

Are the 84 dev dates on which 1306 opened exactly at its previous close concentrated on large market moves
(which would suggest stale 1306 opens), or spread like ordinary days?
* The P2-4 dev panel (build_out/p2_20261006T002928Z/panel_dev.csv) is verified against its MANIFEST.json.
* Only date, ticker, ao_1306_gap_raw and ao_topix_gap are loaded, one row per date; both columns must be identical
  across the tickers of each date (else STOP).
* Z = the dates with ao_1306_gap_raw == 0; there must be 84.
* Quintiles of |ao_topix_gap| over all 1,708 dev dates (cut points in %), and the sd of ao_topix_gap.
* The count of Z in each quintile (Q1 smallest ... Q5 largest); the median and maximum of |ao_topix_gap| over Z, in %.
* Reading rule (fixed by Isaiah on 2026-10-05 before this script ran): "no evidence of stale 1306 opens" if at most
  2 dates of Z are in Q5. Otherwise STOP before the switch (D8 reopens).
Writes reports/P2_3b_d8_gate.md. usage: python tools/p2_3b_d8_zero_gate.py
"""
from __future__ import annotations

import hashlib
import json
import os
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
PANEL_DIR = Path(os.environ["HOME"]) / "Desktop" / "FX_Project" / "build_out" / "p2_20261006T002928Z"
COLS = ["date", "ticker", "ao_1306_gap_raw", "ao_topix_gap"]
N_ZERO = 84
MAX_IN_Q5 = 2


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def main() -> int:
    out = []
    say = out.append
    m = json.loads((PANEL_DIR / "MANIFEST.json").read_text(encoding="utf-8"))
    got, want = sha256(PANEL_DIR / "panel_dev.csv"), m["outputs"]["panel_dev.csv"]["sha256"]
    say("# P2-3b: D8 zero-gap gate (gap-only, dev)")
    say("")
    say(f"Generated by `tools/p2_3b_d8_zero_gate.py`. Panel `build_out/{PANEL_DIR.name}/panel_dev.csv`, SHA-256 `{got}`, "
        f"equal to its MANIFEST entry: {got == want}. Columns: " + ", ".join(f"`{c}`" for c in COLS) + ".")
    say("")
    if got != want:
        say("**STOP: the panel does not hash to its MANIFEST entry.**")
        return finish(out, 2)
    raw = pd.read_csv(PANEL_DIR / "panel_dev.csv", usecols=COLS, dtype=str, keep_default_na=False)
    assert set(raw.columns) == set(COLS), "loaded columns differ from the check's list"
    same = {c: bool((raw.groupby("date")[c].nunique() == 1).all()) for c in COLS[2:]}
    say("- Identical across the tickers of every date: " + "; ".join(f"`{c}` {v}" for c, v in same.items()))
    if not all(same.values()):
        say("")
        say("**STOP: a gap column differs across tickers.**")
        return finish(out, 2)
    d = raw.groupby("date", sort=True)[COLS[2:]].first().apply(pd.to_numeric).astype(float)
    a = d["ao_topix_gap"].abs()
    z = d.index[d["ao_1306_gap_raw"] == 0.0]
    say(f"- Dev dates: {len(d)}; Z (ao_1306_gap_raw == 0): {len(z)}; equals {N_ZERO}: {len(z) == N_ZERO}")
    if len(z) != N_ZERO:
        say("")
        say(f"**STOP: Z has {len(z)} dates, not {N_ZERO}.**")
        return finish(out, 2)
    cuts = np.quantile(a, [0.2, 0.4, 0.6, 0.8])
    q = pd.cut(a, bins=[-np.inf, *cuts, np.inf], labels=["Q1", "Q2", "Q3", "Q4", "Q5"])
    say(f"- sd of ao_topix_gap over all dev dates: {100 * d['ao_topix_gap'].std():.3f}%")
    say("- Quintile cut points of |ao_topix_gap| (20/40/60/80%): " + ", ".join(f"{100 * c:.3f}%" for c in cuts))
    say("")
    say("| Quintile of |ao_topix_gap| | all dev dates | dates of Z |")
    say("|---|---|---|")
    counts = {}
    for lab in ["Q1", "Q2", "Q3", "Q4", "Q5"]:
        counts[lab] = int((q.loc[z] == lab).sum())
        say(f"| {lab} | {int((q == lab).sum())} | {counts[lab]} |")
    say("")
    say(f"- |ao_topix_gap| over Z: median {100 * a.loc[z].median():.3f}%, maximum {100 * a.loc[z].max():.3f}%")
    ok = counts["Q5"] <= MAX_IN_Q5
    say("")
    say(f"Reading rule (fixed beforehand): at most {MAX_IN_Q5} dates of Z in Q5. Dates of Z in Q5: {counts['Q5']}.")
    say("")
    say("**" + ("Gate passed: no evidence of stale 1306 opens." if ok else
                "STOP: more than 2 dates of Z in Q5; D8 reopens.") + "**")
    say("")
    say("Blinding: gap columns only (dev). No target and no predictor column was loaded.")
    return finish(out, 0 if ok else 3)


def finish(out, rc):
    text = "\n".join(out) + "\n"
    (ROOT / "reports" / "P2_3b_d8_gate.md").write_text(text, encoding="utf-8")
    print(text)
    return rc


if __name__ == "__main__":
    sys.exit(main())
