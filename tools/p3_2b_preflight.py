"""P3-2b step d: the early-window count for T6 (DQ4, D4.3). DEV ONLY; TARGET-ONLY COUNTS.

The dev panel's SHA-256 is checked against the registry before it is read (tools/p3_0b_preflight.verify_panel). The
panel is loaded with io.load_dev and targets.add_targets, and the P3-0b Part A rule is applied (imported:
p3_0b_preflight.sample_keep), which uses the predictors only through non-missingness. Reported: kept rows and T_source
(asserted equal to reports/P3_0b_preflight.md); K, the kept unique dates before 2017-09-27; K16, those before
2016-09-28 (information); the kept rows per ticker on the K dates. The two dates are read from
docs/P3_COST_INPUTS.json (flag4_windows: 5706 and 5711). No predictor value enters any computation.
Gate: 398 <= K <= 1,439 and 160 <= K16 <= K. Writes reports/P3_2b_preflight.md and nothing else.
usage: python tools/p3_2b_preflight.py
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "tools"))
from p3_0b_preflight import sample_keep, verify_panel  # noqa: E402
from ofilt.drift import io as IO  # noqa: E402
from ofilt.drift import targets as TG  # noqa: E402
from ofilt.drift.spec import Spec  # noqa: E402


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--panel", type=Path, default=IO.DATA_DIR / IO.DEV_FILE)
    ap.add_argument("--out", type=Path, default=ROOT / "reports" / "P3_2b_preflight.md")
    a = ap.parse_args(argv)
    spec = Spec.load()
    digest = verify_panel(a.panel, spec)                          # before the file is read
    pre = (ROOT / "reports" / "P3_0b_preflight.md").read_text(encoding="utf-8")
    exp_rows = int(re.search(r"^- Kept rows: \*\*(\d+)\*\*$", pre, re.M).group(1))
    exp_dates = int(re.search(r"^- Kept unique dates \(T_source\): \*\*(\d+)\*\*$", pre, re.M).group(1))
    win = json.loads((ROOT / "docs" / "P3_COST_INPUTS.json").read_text(encoding="utf-8"))["flag4_windows"]
    cut, cut16 = pd.Timestamp(win["5706"]["before"]), pd.Timestamp(win["5711"]["before"])
    df = TG.add_targets(IO.load_dev(a.panel, spec), spec)
    keep = sample_keep(df, spec)
    k = df.loc[keep, ["date", "ticker"]]
    n_rows, n_dates = len(k), int(k["date"].nunique())
    if (n_rows, n_dates) != (exp_rows, exp_dates):
        raise SystemExit(f"STOP: kept rows {n_rows} vs {exp_rows}; T_source {n_dates} vs {exp_dates}")
    early = k[k["date"] < cut]
    K = int(early["date"].nunique())
    K16 = int(k.loc[k["date"] < cut16, "date"].nunique())
    per_ticker = early["ticker"].astype(str).value_counts().reindex(list(IO.TICKERS), fill_value=0)
    gate = (398 <= K <= n_dates) and (160 <= K16 <= K)
    L = ["# P3-2b pre-flight: the T6 early window (dev; target-only counts)", "",
         f"Generated by `tools/p3_2b_preflight.py`. Dev panel SHA-256 `{digest}`, equal to the spec's dev-panel hash "
         "(AM-04) and to `docs/PASS2_INPUTS.json` (checked before the file was read). Targets built by "
         "`targets.add_targets`; the P3-0b Part A rule imported from `tools/p3_0b_preflight.py`. Dates from "
         "`docs/P3_COST_INPUTS.json` (`flag4_windows`).", "",
         f"- Kept rows: {n_rows}; T_source: {n_dates} (equal to `reports/P3_0b_preflight.md`: True)",
         f"- K, kept unique dates before {cut.date()}: **{K}**",
         f"- K16, kept unique dates before {cut16.date()} (information): {K16}",
         "- Kept rows per ticker on the K dates: " + ", ".join(f"{t} {int(per_ticker[t])}" for t in IO.TICKERS),
         f"- Gate (398 <= K <= {n_dates} and 160 <= K16 <= K): {gate}", ""]
    md = "\n".join(L)
    if not gate:
        print(md)
        raise SystemExit(f"STOP (gate): K {K}, K16 {K16}")
    a.out.write_text(md, encoding="utf-8")
    print(md, end="")
    return 0


if __name__ == "__main__":
    sys.exit(main())
