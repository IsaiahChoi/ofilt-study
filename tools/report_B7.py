"""B7: dev-calibrated simulation PILOT (final in Pass 4).

  OFILT_RUN_SEALED=1 python tools/report_B7.py              # real dev: ONE sealed fit for all reps
  python tools/report_B7.py --synthetic [--reps N]           # dry run on a synthetic stand-in

Every regression here is on a SIMULATED target y_sim = fc* + b_sim e* + resid*,
built by DevCalibrator from the sealed blind fit (Flag 8 exception). Real mode
writes reports/B_sim_pilot.md(+.json); dry runs write to /tmp and log to a temp file.
"""
from __future__ import annotations

import argparse
import json
import sys
import tempfile
import time
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from ofilt.drift import inference as I  # noqa: E402
from ofilt.drift import io as IO  # noqa: E402
from ofilt.drift import sim as S  # noqa: E402
from ofilt.drift import targets as TG  # noqa: E402
from ofilt.drift.spec import Spec  # noqa: E402

B_GRID = (0.0, 0.10, 0.25, 0.40)
T_SHORT = 983
SIZE_BAND = (0.03, 0.07)


def run_cell(cal, spec, reps, T_out, b_sim, seed0):
    rej = cov = 0
    est, ses = [], []
    for r in range(reps):
        y = cal.draw(b_sim, 0.0, seed=seed0 + r, n_dates=T_out)
        p = I.fit_dk(I.build_design(y, spec, target="y_sim"), spec).param("usdjpy_ret")
        rej += p["p"] < spec.alpha
        cov += p["ci"][0] <= b_sim <= p["ci"][1]
        est.append(p["estimate"]); ses.append(p["se"])
    rr, cr, sd = rej / reps, cov / reps, float(np.std(est, ddof=1))
    return dict(T=T_out, b_sim=b_sim, reps=reps, lag=Spec.dk_lag(int(T_out)), seed0=seed0,
                reject=rr, reject_mcse=float(np.sqrt(rr * (1 - rr) / reps)),
                coverage=cr, coverage_mcse=float(np.sqrt(cr * (1 - cr) / reps)),
                mean_b=float(np.mean(est)), sd_b=sd, mean_se=float(np.mean(ses)),
                se_over_sd=float(np.mean(ses) / sd))


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--synthetic", action="store_true")
    ap.add_argument("--reps", type=int, default=500)
    a = ap.parse_args()
    spec = Spec.load()
    if a.synthetic:
        S.BLIND_FIT_LOG_PATH = Path(tempfile.mkdtemp()) / "BLIND_FIT_LOG"
        base = S.synthetic_panel(1708, b=0.4, a2=-0.2, seed=spec.seed + 7, p_excl=0.03)
        source, out = "SYNTHETIC STAND-IN (dry run; true b = 0.4)", Path("/tmp/B_sim_pilot_DRYRUN")
    else:
        base = TG.add_targets(IO.load_dev(), spec)
        source, out = "real dev residuals and fitted controls (ONE sealed blind fit)", ROOT / "reports" / "B_sim_pilot"
    log = S.BLIND_FIT_LOG_PATH
    n_log0 = len(log.read_text().splitlines()) if log.exists() else 0
    t0 = time.time()
    cal = S.DevCalibrator(base, spec)                       # the ONE sealed fit
    t_fit = time.time() - t0
    rows, t_cells = [], time.time()
    for ci, T_out in enumerate((cal.T, T_SHORT)):
        for bi, b in enumerate(B_GRID):
            rows.append(run_cell(cal, spec, a.reps, T_out, b, spec.seed + 100_000 * (1 + ci) + 10_000 * bi))
            print(f"done T={T_out} b={b}: reject={rows[-1]['reject']:.3f}", flush=True)
    t_all = time.time() - t_cells
    n_fits = len(log.read_text().splitlines()) - n_log0
    if n_fits != 1:
        raise SystemExit(f"expected exactly one sealed fit, log grew by {n_fits}")
    size = {r["T"]: r for r in rows if r["b_sim"] == 0.0}
    flags = [f"T={t}: size {r['reject']:.1%} outside [3%, 7%]" for t, r in size.items()
             if not SIZE_BAND[0] <= r["reject"] <= SIZE_BAND[1]]

    def tab():
        h = ["| T | lag | b_sim | reject H0: b=0 (MC SE) | coverage of 95% CI (MC SE) | mean b_hat | sd b_hat | mean SE | SE/sd |",
             "|---|---|---|---|---|---|---|---|---|"]
        for r in rows:
            h.append(f"| {r['T']} | {r['lag']} | {r['b_sim']:.2f} | {r['reject']:.3f} ({r['reject_mcse']:.3f}) | "
                     f"{r['coverage']:.3f} ({r['coverage_mcse']:.3f}) | {r['mean_b']:+.4f} | {r['sd_b']:.4f} | "
                     f"{r['mean_se']:.4f} | {r['se_over_sd']:.3f} |")
        return "\n".join(h)

    md = f"""# B7: dev-calibrated simulation pilot. **PILOT; final in Pass 4.**

Generated by `tools/report_B7.py`. Source: {source}.

**Simulator.** `DevCalibrator`: ONE sealed blind fit of abn_oc on the full primary design (Flag 8
exception; coefficients never leave the function), then for each rep a stationary bootstrap over
whole dates (Politis-Romano, mean block {cal.mean_block:g}, wrap-around) of the estimation sample's
{cal.T} dates: y_sim = fitted_controls* + b_sim * e* + 0 * eur* + residuals*. Each simulated panel has
T dates drawn from the {cal.T} source dates (T = {cal.T} = dev estimation-sample length, and T = {T_SHORT}
as specified in the prompt).

**Inference (as specified, unchanged):** pooled OLS, ticker FE, common FX block, ticker-specific
spy/copx slopes, Driscoll-Kraay Bartlett SEs at lag floor(4(T/100)^(2/9)), no small-sample
correction, normal reference, two-sided alpha = {spec.alpha}. {a.reps} reps per cell; seeds in the JSON.

{tab()}

**Size (b_sim = 0).** {"; ".join(f"T={t}: {r['reject']:.1%} (MC SE {r['reject_mcse']:.1%})" for t, r in size.items())}.
Pilot band [3%, 7%]: **{"FLAG: " + "; ".join(flags) if flags else "both within the band"}**. The inference is not changed
here; the Pass 4 size rule (2000 reps, [3.5%, 6.5%], else stationary block bootstrap) decides.

**No-leak check.** At b_sim = 0 the mean b_hat is {size[cal.T]['mean_b']:+.4f} (T = {cal.T}) and
{size[T_SHORT]['mean_b']:+.4f} (T = {T_SHORT}), i.e. centred on b_sim, as the B5 algebra requires
(residuals = M_X eps carry no b).

**Runtime.** Sealed fit {t_fit:.1f} s; {len(rows) * a.reps} simulated fits in {t_all:.0f} s
({1000 * t_all / (len(rows) * a.reps):.0f} ms per rep, about 2/3 of it in the frozen fingerprint guard).

**Blinding.** Exactly one sealed fit in this run (log grew by {n_fits}). Every regression above is on a
simulated target; no output relates a real target to FX.
"""
    out.parent.mkdir(parents=True, exist_ok=True)
    out.with_suffix(".md").write_text(md, encoding="utf-8")
    out.with_suffix(".json").write_text(json.dumps(dict(source=source, T_source=cal.T, rows=rows, flags=flags,
                                                        t_fit=t_fit, t_cells=t_all), indent=1), encoding="utf-8")
    print(md)
    return 0


if __name__ == "__main__":
    sys.exit(main())
