_FLAGS = ("boj_day", "sq_day", "sq_major", "exdiv_day")


def full_panel(n_dates, seed, signal=0.0, pure_noise=False):
    """masked_panel plus synthetic values for the 13 PRE_OPEN columns it lacks, so M7
    (which needs all 20) can run. Optional planted NONLINEAR signal in the target:
    signal * (1[gap_adj_lag1 > 0] * 1[oc_lag1 > 0] - 1/4), an interaction of thresholds
    that no linear model in the ladder can represent."""
    df = masked_panel(n_dates, seed=seed)
    rng = np.random.default_rng(seed + 7)
    n = len(df)
    for c in ("eurusd_rv", "ewj_oc", "fcx_oc", "gap_adj_lag1", "oc_lag1", "range_lag1", "topix_oc_lag1"):
        df[c] = rng.standard_normal(n)
    for c in _FLAGS:
        df[c] = (rng.random(n) < 0.05).astype(float)
    df["div_exdate"] = df["exdiv_day"] * 20.0
    df["us_n_sessions"] = 1.0
    if pure_noise:
        df["abn_oc"] = rng.standard_normal(n) * 0.013
    if signal:
        df["abn_oc"] = df["abn_oc"] + signal * (((df.gap_adj_lag1 > 0) & (df.oc_lag1 > 0)).astype(float) - 0.25)
    assert schema.PRE_OPEN_FEATURES <= set(df.columns)
    return B.mark_synthetic(df)


def oos_r2(pred, model, bench="M1"):
    p = pred.pivot_table(index=["date", "ticker"], columns="model", values="yhat")
    y = pred[pred.model == model].set_index(["date", "ticker"]).y.reindex(p.index)
    return 1.0 - float(((y - p[model]) ** 2).sum() / ((y - p[bench]) ** 2).sum())


class TestM7(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.spec = Spec.load()
        cls.df = full_panel(800, seed=41)
        cut = np.sort(cls.df.date.unique())[600]
        tr = (cls.df.date < cut) & ~cls.df.excl_inference
        cls.train = cls.df[tr].reset_index(drop=True)
        cls.test = cls.df[cls.df.date >= cut].reset_index(drop=True)
        cls.y = cls.train.abn_oc.to_numpy()

    def frame(self, d):
        return pd.concat([d[["date", "ticker"]], schema.select_features(d, list(M7.features))], axis=1)

    def test_spec_and_features(self):
        self.assertEqual(self.spec.raw("forecast.models.M7"), M7_SPEC)
        self.assertEqual(set(M7.features), set(schema.PRE_OPEN_FEATURES))
        self.assertEqual(len(M7.features), 20)
        self.assertNotIn(gbm.NOISE, M7.features)          # generated by the model, not a panel column
        schema.assert_features_allowed(list(M7.features))
        self.assertIs(REGISTRY["M7"], M7)
        self.assertEqual(gbm.GRID, tuple((d, n) for d in M7_SPEC["grid"]["max_depth"]
                                         for n in M7_SPEC["grid"]["max_iter"]))

    def test_fixed_parameters_explicit(self):
        c = ctx(self.spec)
        m = M7(); m.fit(self.frame(self.train), self.y, c)
        p = m.model.get_params()
        self.assertIs(p["early_stopping"], False)            # explicit; sklearn's default is 'auto'
        self.assertEqual((p["learning_rate"], p["min_samples_leaf"], p["l2_regularization"]), (0.03, 100, 1.0))
        self.assertEqual(p["random_state"], c.seed)
        self.assertEqual((p["max_depth"], p["max_iter"]), (m.chosen["max_depth"], m.chosen["max_iter"]))
        self.assertEqual(m.model.n_iter_, m.chosen["max_iter"])  # no early stopping happened
        self.assertEqual(m.n_fit_rows, len(self.y))              # winner refit on the full fold

    def test_tuning(self):
        c = ctx(self.spec)
        Xtr = self.frame(self.train)
        m = M7(); m.fit(Xtr, self.y, c)
        keys = {gbm.grid_key(d, n) for d, n in gbm.GRID}
        self.assertEqual(set(m.chosen["val_mse"]), keys)
        best = min(gbm.GRID, key=lambda g: (m.chosen["val_mse"][gbm.grid_key(*g)], g))
        self.assertEqual((m.chosen["max_depth"], m.chosen["max_iter"]), best)
        # the chosen candidate's validation MSE is reproducible by an independent fit on the inner rows
        val = tuning_split(Xtr)
        Z = m._matrix(Xtr, gbm.draw_noise(c.seed, gbm.TRAIN_STREAM, len(Xtr)))
        est = M7.estimator(*best, c.seed).fit(Z[~val], self.y[~val])
        mse = float(np.mean((self.y[val] - est.predict(Z[val])) ** 2))
        self.assertEqual(mse, m.chosen["val_mse"][gbm.grid_key(*best)])
        self.assertLess(Xtr.date[~val].max(), Xtr.date[val].min())

    def test_noise_column(self):
        c = ctx(self.spec)
        Xtr, Xte = self.frame(self.train), self.frame(self.test)
        a = M7(); a.fit(Xtr, self.y, c)
        b = M7(); b.fit(Xtr, self.y, c)
        pa = a.predict(Xte, c)
        self.assertTrue(np.array_equal(pa, b.predict(Xte, c)))                    # deterministic
        Xn = Xte.copy(); Xn[gbm.NOISE] = a.test_noise(len(Xte), c)
        self.assertTrue(np.array_equal(pa, a.predict(Xn, c)))                     # supplied == generated
        n1 = gbm.draw_noise(c.seed, gbm.TEST_STREAM, 50)
        self.assertTrue(np.array_equal(n1, gbm.draw_noise(c.seed, gbm.TEST_STREAM, 80)[:50]))  # row-order prefix
        self.assertFalse(np.array_equal(n1, gbm.draw_noise(c.seed, gbm.TRAIN_STREAM, 50)))
        self.assertFalse(np.array_equal(n1, gbm.draw_noise(c.seed + 1, gbm.TEST_STREAM, 50)))

    def test_unseen_ticker_raises(self):
        c = ctx(self.spec)
        m = M7(grid=((2, 50),)); m.fit(self.frame(self.train), self.y, c)
        bad = self.frame(self.test).copy(); bad.loc[0, "ticker"] = "9999"
        with self.assertRaises(ValueError):
            m.predict(bad, c)

    def test_engine_and_planted_signal(self):
        """In the engine with its comparator M1 (P27: M7 runs in its own call). A planted
        nonlinear signal gives positive OOS R2 vs M1."""
        df = full_panel(700, seed=5, signal=0.02)
        pred, folds = F.walk_forward(df, {"M1": M1, "M7": M7}, self.spec)
        self.assertEqual(sorted(pred.model.unique()), ["M1", "M7"])
        k1 = pred[pred.model == "M1"][["date", "ticker"]].reset_index(drop=True)
        k7 = pred[pred.model == "M7"][["date", "ticker"]].reset_index(drop=True)
        self.assertTrue(k1.equals(k7))                                             # identical rows
        ch = folds[folds.model == "M7"].chosen
        self.assertTrue(all((c["max_depth"], c["max_iter"]) in gbm.GRID for c in ch))
        r2 = oos_r2(pred, "M7")
        self.assertGreater(r2, 0.05, f"OOS R2 vs M1 on a planted signal: {r2:.4f}")

    def test_pure_noise(self):
        """No signal: M7 should not beat M1 out of sample (P28 reported -0.011)."""
        r2 = [oos_r2(F.walk_forward(full_panel(700, seed=s, pure_noise=True), {"M1": M1, "M7": M7},
                                    self.spec)[0], "M7") for s in (11, 12, 13)]
        self.assertLess(np.mean(r2), 0.0, f"pure-noise OOS R2 vs M1: {np.round(r2, 4)}")
        self.assertGreater(np.mean(r2), -0.10, f"pure-noise OOS R2 vs M1: {np.round(r2, 4)}")


if __name__ == "__main__":
    unittest.main()
